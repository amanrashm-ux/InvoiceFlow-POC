CREATE OR REPLACE VIEW INVOICEFLOW.GOLD.VW_INVOICEFLOW_KPIS AS
SELECT
 (SELECT COUNT(*) FROM INVOICEFLOW.BRONZE.RAW_DOMAIN_EVENTS WHERE EVENT_TYPE='invoice.created') AS INVOICE_COUNT,
 (SELECT COUNT(*) FROM INVOICEFLOW.BRONZE.RAW_DOMAIN_EVENTS WHERE EVENT_TYPE='invoice.accepted') AS ACCEPTED_COUNT,
 (SELECT COUNT(*) FROM INVOICEFLOW.BRONZE.RAW_DOMAIN_EVENTS WHERE EVENT_TYPE='financing.approved') AS FINANCING_APPROVAL_COUNT,
 (SELECT COUNT(*) FROM INVOICEFLOW.BRONZE.RAW_DOMAIN_EVENTS WHERE EVENT_TYPE='payment.disbursed') AS SIMULATED_DISBURSEMENT_COUNT,
 (SELECT COUNT(*) FROM INVOICEFLOW.BRONZE.RAW_DOMAIN_EVENTS WHERE EVENT_TYPE='reconciliation.completed') AS RECONCILIATION_COUNT;
