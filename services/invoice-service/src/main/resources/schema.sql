CREATE TABLE IF NOT EXISTS invoices (
 invoice_id VARCHAR(40) PRIMARY KEY, supplier_id VARCHAR(40) NOT NULL, buyer_id VARCHAR(40) NOT NULL,
 invoice_number VARCHAR(80) NOT NULL UNIQUE, currency VARCHAR(3) NOT NULL, amount NUMERIC(18,2) NOT NULL,
 issue_date DATE NOT NULL, due_date DATE NOT NULL, status VARCHAR(30) NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS outbox_events (
 event_id VARCHAR(40) PRIMARY KEY, routing_key VARCHAR(120) NOT NULL, event_json CLOB NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP, published_at TIMESTAMP WITH TIME ZONE
);
